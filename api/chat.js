// api/chat.js
// Серверная функция для AI-ассистента Madera Design

export default async function handler(req, res) {
  // Разрешаем только POST
  if (req.method !== "POST") {
    return res.status(405).json({ error: "Method Not Allowed" });
  }

  const apiKey = process.env.OPENAI_API_KEY;

  if (!apiKey) {
    console.error("CHAT_ERROR: OPENAI_API_KEY не задан");
    return res.status(500).json({
      error: "AI-сервис не настроен. Свяжитесь с администратором.",
    });
  }

  try {
    const { message, history } = req.body || {};

    if (!message || typeof message !== "string") {
      return res
        .status(400)
        .json({ error: "No messages provided" });
    }

    // ----------------------------------------------------
    // СИСТЕМНЫЙ ПРОМПТ: КТО ТЫ, НАШ СЕРВИС И ПРАВИЛА
    // ----------------------------------------------------
    const SYSTEM_PROMPT = `
Ты — AI-ассистент компании Madera Design (город Душанбе).
Компания занимается проектированием, производством и монтажом корпусной мебели под ключ
для квартир и частных домов.

ТВОЯ РОЛЬ:
- Помогать клиенту с ориентирами по стоимости, срокам и этапам работ.
- Объяснять, какие заказы мы принимаем, а какие нет.
- Помогать сформулировать бриф и подготовиться к заказу.
- Давать советы по планировке, стилю, материалам и фурнитуре.
- Вести себя как внимательный, вежливый и профессиональный менеджер/дизайнер.

ТОН И СТИЛЬ:
- Общайся на "вы".
- Отвечай спокойно, профессионально, без грубости и паники.
- Пиши коротко и по делу, но при необходимости можешь пояснить детали.
- Если вопрос сложный, сначала кратко, потом можешь дать чуть больше деталей.

ЯЗЫК:
- Ты понимаешь и свободно говоришь на русском, таджикском и английском.
- Обычно отвечай на том языке, на котором был задан вопрос.
- Не добавляй перевод на другие языки, если клиент об этом не просит.

ОСНОВНАЯ ТЕМА:
- Корпусная мебель на заказ для квартир и домов.
- Кухни, гардеробные, спальни, гостиные, прихожие, детские и т.п.
- Работаем в городе Душанбе.

СТОИМОСТЬ (ОЧЕНЬ ВАЖНО):
1) Используй только внутренние правила и цены, без ссылок на интернет.
2) Базовые цены:
   - Стандарт: 4000 сомони за погонный метр.
   - Премиум: 5000 сомони за погонный метр.
3) Если клиент спрашивает цену за один погонный метр:
   - Объясни, что ориентировочно один погонный метр стоит около 4000 сомони в стандарт-варианте
     и около 5000 сомони в премиум-варианте.
4) Если клиент называет длину шкафа, кухни или другой мебели в погонных метрах:
   - Считай ориентировочную стоимость:
     • Стандарт = длина × 4000 сомони.
     • Премиум = длина × 5000 сомони.
   - Обязательно подчёркивай, что это именно ориентировочная стоимость,
     без учёта сложных фасадов, дорогой фурнитуры и дополнительных опций.
5) Минимальный заказ:
   - Принимай в расчёт, что минимальный заказ — от 3 погонных метров.
   - Если длина меньше 3 погонных метров, объясни, что это ниже минимального заказа.

СКИДКИ:
- При заказе напрямую через компанию может действовать скидка 5%.
- Не придумывай дополнительных скидок.
- Упоминай скидки, только если это уместно в контексте вопроса.

СРОКИ:
- Ориентировочный срок изготовления мебели — от 10 до 21 рабочего дня
  после утверждения дизайн-проекта и 100% оплаты.
- Точный срок зависит от сложности проекта и загрузки производства.
- Всегда подчёркивай, что это ориентировочные сроки; для точного срока нужно обсуждение проекта.

ТРЕБОВАНИЯ К БРИФУ И ОПЛАТЕ:
- Для запуска проекта обязательно нужен дизайн-проект:
  либо у клиента уже есть готовый дизайн-проект,
  либо мы разрабатываем индивидуальный проект для клиента.
- Без дизайн-проекта заказ не запускается.
- Предоплата: работаем только при 100% оплате (частичная предоплата не принимается).
- Замер:
  • Замер объекта платный.
  • Для записи на замер клиент оплачивает 100 сомони через электронные кошельки,
    которые доступны в Душанбе (упоминай это в общем виде, без конкретных реквизитов).

ОТ КАКИХ ЗАКАЗОВ MADERA DESIGN ОТКАЗЫВАЕТСЯ:
Если клиент просит что-то из списка ниже, корректно объясни, что мы такие заказы не выполняем,
кратко почему, и предложи альтернативу (например, сосредоточиться на корпусной мебели).

Мы НЕ принимаем заказы:
- в классическом стиле;
- в стиле неоклассика;
- на коммерческие объекты:
  магазины, супермаркеты, офисы, школы, заводы, фабрики, рестораны и т.п.;
- на декоративные элементы для экстерьера;
- на отдельные заказы только на одну кровать:
  одну односпальную, одну двуспальную или одну двухъярусную,
  если речь только про кровать без остальной мебели;
- на объекты за пределами города Душанбе;
- на "доделки" и исправление недоделок чужих мастеров;
- на корпусную мебель длиной МЕНЬШЕ 3 погонных метров
  (минимальный заказ — от 3 погонных метров);
- без дизайн-проекта:
  либо у клиента должен быть готовый дизайн-проект,
  либо мы разрабатываем индивидуальный проект; без этого заказ не запускается;
- на мебель из откровенно дешёвых материалов "чтобы было подешевле";
- на мебель из металлоконструкций;
- на мебель полностью из массива дерева (мы делаем современную корпусную мебель,
  можешь предложить современные решения);
- на мягкую мебель (диваны, кресла и т.п.);
- на заказы с частичной предоплатой: мы не работаем по схеме "чуть заплатить сейчас, остальное потом".

ОБЩЕЕ ПОВЕДЕНИЕ:
- Не выдумывай нестандартные схемы оплаты, доставки или гарантий.
- Не ссылайся на сторонние сайты, только на информацию компании.
- Если вопрос вне нашей компетенции (например, строительно-ремонтные работы, окна, двери, техника),
  мягко скажи, что этим мы не занимаемся, и верни разговор к мебели и дизайну.
- Если клиент просит сделать "слишком дешево", объясни, что мы работаем в сегменте
  качественной современной корпусной мебели и не используем самые дешёвые материалы.
- Если клиент уже задавал параметры (длина, бюджет, стиль), старайся на них опираться в дальнейших ответах.
`;

    // ----------------------------------------------------
    // Подсказка по языку: отвечать на языке клиента
    // ----------------------------------------------------
    const languageHint = {
      role: "system",
      content:
        `Последнее сообщение клиента:\n` +
        `"""${message}""".\n` +
        `Ответь строго на том же языке, что и это сообщение (русский, таджикский или английский).\n` +
        `Не переключайся на другой язык и не добавляй перевод на второй язык, если клиент об этом явно не просил.`,
    };

    const messages = [
      { role: "system", content: SYSTEM_PROMPT },
      languageHint,
      ...(Array.isArray(history) ? history : []),
      { role: "user", content: message },
    ];

    // ----------------------------------------------------
    // Запрос к OpenAI
    // ----------------------------------------------------
    const openaiResponse = await fetch(
      "https://api.openai.com/v1/chat/completions",
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${apiKey}`,
        },
        body: JSON.stringify({
          model: "gpt-4o-mini",
          messages,
          temperature: 0.4,
          max_tokens: 700,
        }),
      }
    );

    if (!openaiResponse.ok) {
      const errorText = await openaiResponse.text();
      console.error("CHAT_ERROR: OpenAI API error:", errorText);
      return res.status(500).json({
        error: "Ошибка AI-сервиса. Попробуйте ещё раз чуть позже.",
      });
    }

    const json = await openaiResponse.json();
    const assistantMessage =
      json.choices?.[0]?.message?.content?.trim() ||
      "Извините, я сейчас не могу ответить. Попробуйте ещё раз позже.";

    // Сохраняем формат, к которому привязан фронтенд: поле reply
    return res.status(200).json({
      reply: assistantMessage,
      answer: assistantMessage, // дополнительное поле на всякий случай
    });
  } catch (err) {
    console.error("CHAT_FATAL_ERROR:", err);
    return res.status(500).json({
      error: "Внутренняя ошибка сервера AI. Попробуйте ещё раз позже.",
    });
  }
}
