module.exports = async (req, res) => {
  if (req.method !== "POST") {
    res.setHeader("Allow", "POST");
    return res.status(405).json({ error: "Method Not Allowed" });
  }

  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) {
    console.error("AI_DESIGNER_ERROR: OPENAI_API_KEY is not set");
    return res.status(500).json({
      error: "AI-сервис не настроен на сервере (нет ключа OPENAI_API_KEY).",
    });
  }

  try {
    const { message, history, systemPrompt } = req.body || {};

    if (!message || typeof message !== "string") {
      return res.status(400).json({ error: "Пустое сообщение." });
    }

    const messages = [];

    messages.push({
      role: "system",
      content:
        typeof systemPrompt === "string" && systemPrompt.trim()
          ? systemPrompt.trim()
          : DEFAULT_SYSTEM_PROMPT,
    });

    if (Array.isArray(history)) {
      history.slice(-10).forEach((item) => {
        if (!item || typeof item.text !== "string") return;
        const role = item.role === "assistant" ? "assistant" : "user";
        messages.push({ role, content: item.text });
      });
    }

    messages.push({ role: "user", content: message });

    const openaiRes = await fetch("https://api.openai.com/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${apiKey}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "gpt-4.1-mini",
        messages,
        temperature: 0.6,
        max_tokens: 800,
      }),
    });

    if (!openaiRes.ok) {
      const errText = await openaiRes.text().catch(() => "");
      console.error("AI_DESIGNER_HTTP_ERROR", openaiRes.status, errText);
      return res.status(502).json({
        error: "Ошибка внешнего AI-сервиса. Попробуйте ещё раз чуть позже.",
      });
    }

    const data = await openaiRes.json();
    const reply =
      data &&
      Array.isArray(data.choices) &&
      data.choices[0] &&
      data.choices[0].message &&
      typeof data.choices[0].message.content === "string"
        ? data.choices[0].message.content.trim()
        : "";

    if (!reply) {
      console.warn("AI_DESIGNER_EMPTY_REPLY", data);
      return res.status(200).json({
        reply:
          "Не получилось получить содержательный ответ от AI-дизайнера. Попробуйте переформулировать вопрос.",
      });
    }

    return res.status(200).json({ reply });
  } catch (err) {
    console.error("AI_DESIGNER_UNEXPECTED_ERROR", err);
    return res.status(500).json({
      error: "Неожиданная ошибка сервера AI-дизайнера.",
    });
  }
};
