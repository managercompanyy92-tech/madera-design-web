export default async function handler(req, res) {
  if (req.method !== "POST") {
    return res.status(405).json({ error: "Method not allowed" });
  }

  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) {
    console.error("AI_DESIGNER_ERROR: OPENAI_API_KEY is not set");
    return res
      .status(500)
      .json({ error: "AI-сервис временно не настроен (нет API-ключа)." });
  }

  try {
    const body = req.body || {};

    // Новый формат: { messages, imageRequest }
    const rawMessages = Array.isArray(body.messages) ? body.messages : null;

    // Старый формат: { message, history }
    const plainMessage = body.message;
    const plainHistory = Array.isArray(body.history) ? body.history : null;

    let conversation = [];

    if (rawMessages && rawMessages.length > 0) {
      conversation = rawMessages.map((m) => ({
        role:
          m.role === "assistant"
            ? "assistant"
            : m.role === "system"
            ? "system"
            : "user",
        content: String(m.content || ""),
      }));
    } else {
      if (plainHistory) {
        conversation = plainHistory.map((m) => ({
          role: m.role === "assistant" ? "assistant" : "user",
          content: String(m.content || ""),
        }));
      }
      if (plainMessage && typeof plainMessage === "string") {
        conversation.push({ role: "user", content: plainMessage });
      }
    }

    const lastUserMsg =
      [...conversation].reverse().find((m) => m.role === "user") || null;
    if (!lastUserMsg) {
      return res
        .status(400)
        .json({ error: "No user message provided in request" });
    }

    const messagesForModel = [
      { role: "system", content: SYSTEM_PROMPT },
      ...conversation,
    ];

    let replyText = "";

    try {
      const completion = await client.chat.completions.create({
        model: "gpt-4.1-mini",
        messages: messagesForModel,
        temperature: 0.4,
        max_tokens: 900,
      });

      replyText =
        completion.choices?.[0]?.message?.content?.trim() ||
        "Готов помочь с идеей дизайна и примерной стоимостью. Уточните, пожалуйста, размеры и стиль мебели.";
    } catch (openAiError) {
      console.error("AI_DESIGNER_OPENAI_ERROR:", openAiError);
      replyText =
        "Извините, сейчас не получилось получить детальный ответ от AI-дизайнера. Попробуйте задать свой вопрос ещё раз или уточните размеры и стиль мебели.";
    }

    // Возвращаем формат, совместимый и со старым, и с новым фронтом:
    // reply — как раньше; text — для нового ai-chat.js.
    return res.status(200).json({
      reply: replyText,
      text: replyText,
    });
  } catch (err) {
    console.error("AI_DESIGNER_ERROR:", err);
    return res.status(500).json({
      error: "Извините, сервис временно недоступен. Попробуйте позже.",
    });
  }
}
